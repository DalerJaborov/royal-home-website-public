/**
 * FAQPage JSON-LD для главной и страницы ипотеки — ОДИН источник для сервера и клиента.
 *
 * Лежит в contracts/ по той же причине, что и SERVICE_SEO: пререндер
 * (api/lib/prerenderSeo.ts) вставляет эту разметку в исходный HTML для
 * скрейперов без JS, а клиентский useSeo (src/pages/Home.tsx, MortgagePage.tsx)
 * обязан передать тот же jsonLd — иначе он читает <script id="seo-page-jsonld">
 * из серверного HTML и тут же удаляет его при монтировании (useSeo всегда
 * зачищает предыдущий per-page JSON-LD), и разметка, ради которой городили
 * пререндер, живёт только до гидратации.
 *
 * Вопросы дублируют то, что сайт и так утверждает на страницах услуг/ипотеки —
 * никакой новой фактуры, только структурирование для поисковиков и ИИ-ассистентов.
 */

function faqJsonLd(items: Array<{ q: string; a: string }>): object {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: items.map((f) => ({
      "@type": "Question",
      name: f.q,
      acceptedAnswer: { "@type": "Answer", text: f.a },
    })),
  };
}

