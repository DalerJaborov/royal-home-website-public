// Server sections merge over defaults so newly added fields keep working
// even when the stored blob predates them.
function mergeCms(server: Partial<CmsData>): CmsData {
  server = normalizeCompanyPublicValue(server);
  return {
    hero: { ...DEFAULT_CMS.hero, ...server.hero,
      variant: server.hero && !server.hero.variant ? server.hero.usePhoto ? 'photo-cards' : 'flat-brand' : server.hero?.variant ?? DEFAULT_CMS.hero.variant },
    banners: { ...DEFAULT_CMS.banners, ...server.banners },
    dushanbeBanner: { ...DEFAULT_CMS.dushanbeBanner, ...server.dushanbeBanner },
    services: server.services ?? DEFAULT_CMS.services,
    blogPosts: server.blogPosts ?? DEFAULT_CMS.blogPosts,
    reels: { ...DEFAULT_CMS.reels, ...server.reels },
    site: normalizeCompanySiteSettings({
      ...DEFAULT_CMS.site,
      ...server.site,
      socialVisibility: { ...DEFAULT_CMS.site.socialVisibility, ...server.site?.socialVisibility },
      pageSeo: { ...DEFAULT_CMS.site.pageSeo, ...server.site?.pageSeo },
    }),
    categoryVisibility: { ...DEFAULT_CMS.categoryVisibility, ...server.categoryVisibility },
    banks: server.banks ?? DEFAULT_CMS.banks,
  };
}

interface CmsContextType {
  cms: CmsData;
  updateHero: (hero: Partial<HeroSettings>) => void;
  updateBanners: (banners: Partial<BannerSettings>) => void;
  updateDushanbeBanner: (banner: Partial<DushanbeBannerSettings>) => void;
  updateServices: (services: ServiceItem[]) => void;
  updateBlogPosts: (posts: BlogPostItem[]) => void;
  updateReels: (reels: Partial<ReelsSettings>) => void;
  updateSite: (site: Partial<SiteSettings>) => void;
  updateCategoryVisibility: (visibility: Partial<CategoryVisibility>) => void;
  updateBanks: (banks: BankItem[]) => void;
  resetToDefault: () => void;
}

const CmsContext = createContext<CmsContextType | null>(null);

export function CmsProvider({ children }: { children: ReactNode }) {
  const cmsQuery = trpc.cms.getAll.useQuery(undefined, { staleTime: 60_000 });
  const [cms, setCms] = useState<CmsData>(() => cmsQuery.data ? mergeCms(cmsQuery.data as Partial<CmsData>) : DEFAULT_CMS);
  const setMutation = trpc.cms.set.useMutation();
  const serverLoaded = useRef(!!cmsQuery.data);

  useEffect(() => {
    if (cmsQuery.data && !serverLoaded.current) {
      serverLoaded.current = true;
      setCms(mergeCms(cmsQuery.data as Partial<CmsData>));
    }
  }, [cmsQuery.data]);

  // Optimistic local update + persist the whole section to the server.
  // Only admin pages call the update functions, so cms.set's admin guard
  // is never hit by regular visitors.
  // Синхронизация ref в эффекте, а не в теле компонента: запись во время рендера
  // делает его нечистым (при повторном проходе React значение уже подменено).
  // Ref нужен только функциям обновления, которые вызываются из обработчиков —
  // к моменту вызова эффект уже отработал.
  const cmsRef = useRef(cms);
  useEffect(() => {
    cmsRef.current = cms;
  }, [cms]);

  const persist = useCallback((key: keyof CmsData, value: CmsData[keyof CmsData]) => {
    setMutation.mutate({ key, value });
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const updateSection = useCallback(<K extends keyof CmsData>(key: K, value: Partial<CmsData[K]>) => {
    const next = { ...cmsRef.current, [key]: { ...cmsRef.current[key], ...value } };
    if (key === 'site') next.site = normalizeCompanySiteSettings(next.site);
    setCms(next);
    persist(key, next[key]);
  }, [persist]);

  const updateHero = useCallback((hero: Partial<HeroSettings>) => updateSection('hero', hero), [updateSection]);
  const updateBanners = useCallback((banners: Partial<BannerSettings>) => updateSection('banners', banners), [updateSection]);
  const updateDushanbeBanner = useCallback((banner: Partial<DushanbeBannerSettings>) => updateSection('dushanbeBanner', banner), [updateSection]);
  const updateSite = useCallback((site: Partial<SiteSettings>) => updateSection('site', site), [updateSection]);

  const updateServices = useCallback((services: ServiceItem[]) => {
    setCms({ ...cmsRef.current, services });
    persist('services', services);
  }, [persist]);

  const updateBlogPosts = useCallback((blogPosts: BlogPostItem[]) => {
    setCms({ ...cmsRef.current, blogPosts });
    persist('blogPosts', blogPosts);
  }, [persist]);

  const updateReels = useCallback((reels: Partial<ReelsSettings>) => updateSection('reels', reels), [updateSection]);

  const updateCategoryVisibility = useCallback(
    (visibility: Partial<CategoryVisibility>) => updateSection('categoryVisibility', visibility),
    [updateSection]
  );

  const updateBanks = useCallback((banks: BankItem[]) => {
    setCms({ ...cmsRef.current, banks });
    persist('banks', banks);
  }, [persist]);

  const resetToDefault = useCallback(() => {
    setCms(DEFAULT_CMS);
    for (const key of Object.keys(DEFAULT_CMS) as (keyof CmsData)[]) {
      persist(key, DEFAULT_CMS[key]);
    }
  }, [persist]);

  return (
    <CmsContext.Provider value={{ cms, updateHero, updateBanners, updateDushanbeBanner, updateServices, updateBlogPosts, updateReels, updateSite, updateCategoryVisibility, updateBanks, resetToDefault }}>
      {children}
    </CmsContext.Provider>
  );
}

// eslint-disable-next-line react-refresh/only-export-components -- Context hook is intentionally colocated with its provider.
export function useCms() {
  const ctx = useContext(CmsContext);
  if (!ctx) throw new Error('useCms must be used within CmsProvider');
  return ctx;
}
