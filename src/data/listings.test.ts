import { describe, expect, it } from "vitest";
import { getDistrictName } from "./listings";

/**
 * Район из строки адреса.
 *
 * Находка автопроверки (PR #14): адрес приходит в ДВУХ форматах с разным
 * порядком частей — «Душанбе, р-н Сино, ул. …» у объектов, заведённых на сайте,
 * и «Исмоили Сомони, Душанбе» у приехавших из CRM (район первым). Везде, кроме
 * страницы объекта, район брали как «вторую часть» — и у всей растущей части
 * каталога районом показывался город: значок терял смысл, фильтр районов
 * в админке состоял из одного «Душанбе», а подбор похожих объектов сравнивал
 * «Душанбе» с «Душанбе» и переставал учитывать район вовсе.
 */

describe("Район берётся по смыслу, а не по позиции", () => {
  it("объект из CRM: район стоит ПЕРВЫМ", () => {
    expect(getDistrictName("Исмоили Сомони, Душанбе")).toBe("Исмоили Сомони");
    expect(getDistrictName("Сино, Душанбе")).toBe("Сино");
  });

  it("объект, заведённый на сайте: город первым, дальше район и улица", () => {
    expect(getDistrictName("Душанбе, р-н Сино, ул. Рудаки 10")).toBe("Сино");
    expect(getDistrictName("Душанбе, Шохмансур, ул. Айни 5")).toBe("Шохмансур");
  });

  it("приставка «р-н» срезается — она часть формата, а не название", () => {
    expect(getDistrictName("Душанбе, р-н Фирдавси")).toBe("Фирдавси");
    expect(getDistrictName("р-н Сино, Душанбе")).toBe("Сино");
  });

  it("улица районом не считается, даже если идёт сразу за городом", () => {
    expect(getDistrictName("Душанбе, ул. Рудаки 10")).toBe("Душанбе");
  });

  it("когда района нет — запасное значение, а не пустая строка на экране", () => {
    expect(getDistrictName("Душанбе")).toBe("Душанбе");
    // Пустая строка запрашивается там, где подпись лучше скрыть, чем врать.
    expect(getDistrictName("Душанбе", "")).toBe("");
  });

  it("лишние пробелы не мешают", () => {
    expect(getDistrictName("  Исмоили Сомони ,  Душанбе ")).toBe("Исмоили Сомони");
  });
});
